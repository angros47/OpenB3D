typedef struct {
    unsigned char* pixels;
    int width;
    int height;
    unsigned char r, g, b, a;
} BB_Buffer;

// Inizializzazione Buffer (RGBA o BGRA a seconda delle esigenze)
static inline BB_Buffer* BB_CreateBuffer(int w, int h) {
    BB_Buffer* b = (BB_Buffer*)malloc(sizeof(BB_Buffer));
    b->pixels = (unsigned char*)calloc(w * h * 4, 1);
    b->width = w; b->height = h;
    b->r = 255; b->g = 255; b->b = 255; b->a = 255;
    return b;
}

static inline void BB_Color(BB_Buffer* buf, unsigned char r, unsigned char g, unsigned char b) {
    buf->r = r; buf->g = g; buf->b = b;
}

static inline void BB_WritePixel(BB_Buffer* buf, int x, int y) {
    if (x < 0 || x >= buf->width || y < 0 || y >= buf->height) return;
    int idx = (y * buf->width + x) * 4;
    buf->pixels[idx]     = buf->r; // Mappa BGRA invertendo qui se serve a FreeBASIC/OpenB3D
    buf->pixels[idx + 1] = buf->g;
    buf->pixels[idx + 2] = buf->b;
    buf->pixels[idx + 3] = 255; // Opaco
}

// 1. RETTANGOLO PIENO o VUOTO (stile BlitzBasic Rect)
static inline void BB_Rect(BB_Buffer* buf, int x, int y, int w, int h, int fill) {
    for (int j = y; j < y + h; j++) {
        for (int i = x; i < x + w; i++) {
            if (fill || i == x || i == x + w - 1 || j == y || j == y + h - 1) {
                BB_WritePixel(buf, i, j);
            }
        }
    }
}

// 2. OVALE PIENO (Algoritmo dei punti medi, pixel pieni privo di antialiasing)
// 2. OVALE (Disegna sempre il bordo. Se fill=1 riempie anche l'interno)
static inline void BB_Oval(BB_Buffer* buf, int xc, int yc, int rx, int ry, int fill) {
    if (rx <= 0 || ry <= 0) return;

    for (int y = -ry; y <= ry; y++) {
        for (int x = -rx; x <= rx; x++) {
            // Equazione standard dell'ellisse riscalata per evitare i numeri decimali (float)
            long long dx = (long long)x * x * ry * ry;
            long long dy = (long long)y * y * rx * rx;
            long long r2 = (long long)rx * rx * ry * ry;
            long long somma = dx + dy;

            if (somma <= r2) {
                if (fill) {
                    // Se fill è attivo, coloriamo ogni pixel interno
                    BB_WritePixel(buf, xc + x, yc + y);
                } else {
                    // Se fill è disattivato, coloriamo il pixel SOLO se si trova sul bordo esterno.
                    // Per capire se siamo sul bordo valutiamo lo "spessore" di 1 pixel lungo i due assi.
                    long long bordo_x = (long long)(abs(x) + 1) * (abs(x) + 1) * ry * ry + dy;
                    long long bordo_y = dx + (long long)(abs(y) + 1) * (abs(y) + 1) * rx * rx;
                    
                    if (bordo_x > r2 || bordo_y > r2) {
                        BB_WritePixel(buf, xc + x, yc + y);
                    }
                }
            }
        }
    }
}

// 5. LINEA (Algoritmo di Bresenham pixel-perfect senza antialiasing)
static inline void BB_Line(BB_Buffer* buf, int x1, int y1, int x2, int y2) {
    int dx = abs(x2 - x1);
    int dy = abs(y2 - y1);
    int sx = (x1 < x2) ? 1 : -1;
    int sy = (y1 < y2) ? 1 : -1;
    int err = dx - dy;

    while (1) {
        BB_WritePixel(buf, x1, y1);

        if (x1 == x2 && y1 == y2) break;
        
        int e2 = 2 * err;
        if (e2 > -dy) {
            err -= dy;
            x1 += sx;
        }
        if (e2 < dx) {
            err += dx;
            y1 += sy;
        }
    }
}


// 3. TEXT DOS RETRO (Disegno del Font Bitmap 8x8 monocromatico, fisso)
static inline void BB_Text(BB_Buffer* buf, int x, int y, const char* text) {
    while (*text) {
        char c = *text;
        if (c >= 32 && c <= 126) {
            int font_idx = c - 32;
            for (int row = 0; row < 8; row++) {
                unsigned char bits = font8x8_dos[font_idx][row];
                for (int col = 0; col < 8; col++) {
                    // Controlla se il bit corrente è impostato a 1 (pixel acceso)
                    if (bits & (1 << (7 - col))) {
                        BB_WritePixel(buf, x + col, y + row);
                    }
                }
            }
        }
        x += 8; // Avanzamento fisso monospace del testo DOS
        text++;
    }
}

// 4. BLIT CON ROTAZIONE E SCALATURA (Pixel pieni, mappatura inversa veloce)
static inline void BB_DrawBufferEx(BB_Buffer* dest, BB_Buffer* src, int destX, int destY, float angle, float scaleX, float scaleY) {
    float rad = angle * 3.14159265f / 180.0f;
    float cosA = cosf(rad);
    float sinA = sinf(rad);
    
    // Calcoliamo le dimensioni della texture sorgente scalata
    int sw = src->width; int sh = src->height;
    int half_sw = sw / 2; int half_sh = sh / 2;
    
    // Raggio massimo per il ciclo di scansione
    int rangeX = (int)(sqrtf(sw*sw + sh*sh) * scaleX) / 2 + 1;
    int rangeY = (int)(sqrtf(sw*sw + sh*sh) * scaleY) / 2 + 1;

    // Mapping inverso: giriamo sui pixel di destinazione e cerchiamo il pixel corrispondente nella sorgente
    for (int dy = -rangeY; dy <= rangeY; dy++) {
        for (int dx = -rangeX; dx <= rangeX; dx++) {
            // Coordinate relative ruotate e scalate all'indietro
            float tx = (dx * cosA + dy * sinA) / scaleX + half_sw;
            float ty = (-dx * sinA + dy * cosA) / scaleY + half_sh;

            int sx = (int)tx; int sy = (int)ty;

            // Se il pixel cade dentro la texture sorgente, lo copiamo
            if (sx >= 0 && sx < sw && sy >= 0 && sy < sh) {
                int src_idx = (sy * sw + sx) * 4;
                // Controllo se il pixel sorgente non è vuoto/nero (Trasparenza colore chiave)
                if (src->pixels[src_idx+3] > 0) { 
                    dest->r = src->pixels[src_idx];
                    dest->g = src->pixels[src_idx+1];
                    dest->b = src->pixels[src_idx+2];
                    BB_WritePixel(dest, destX + dx, destY + dy);
                }
            }
        }
    }
}

static inline void BB_FreeBuffer(BB_Buffer* b) { free(b->pixels); free(b); }

